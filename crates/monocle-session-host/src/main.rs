#[cfg(test)]
#[allow(non_snake_case)]
mod tests {
    use super::*;

    /// Verify that MONOCLE_SESSION_ID env var is not read or forwarded by the
    /// session-host binary (BC hook constraint BC-HOOK-030).
    ///
    /// The session_id is passed as a CLI arg (--session-id), never via env.
    /// Hooks must NOT see MONOCLE_SESSION_ID in their environment.
    #[test]
    fn test_BC_HOOK_030_monocle_session_id_env_set_not_read_by_hooks() {
        // Verify the binary does NOT expose MONOCLE_SESSION_ID via env inheritance.
        // This is enforced structurally: step_build_command() uses std::env::vars()
        // for env inheritance, and MONOCLE_SESSION_ID is not set in the daemon's
        // environment (the daemon never sets it). The hook scripts must NOT be able
        // to read this variable.
        //
        // This test asserts that the session_id comes from CliArgs.session_id
        // (parsed from --session-id CLI arg), NOT from any env var.
        let args = CliArgs {
            session_id: "test-session-uuid".to_string(),
            runtime_dir: std::path::PathBuf::from("/tmp"),
            binary: std::path::PathBuf::from("/bin/cat"),
            args: vec![],
            env: std::collections::HashMap::new(),
            cwd: std::path::PathBuf::from("/tmp"),
        };

        // session_id is from args struct, not from env.
        assert_eq!(args.session_id, "test-session-uuid");
        // MONOCLE_SESSION_ID is not in the env map.
        assert!(
            !args.env.contains_key("MONOCLE_SESSION_ID"),
            "BC-HOOK-030: MONOCLE_SESSION_ID must not be in the session env overlay"
        );
    }
}
